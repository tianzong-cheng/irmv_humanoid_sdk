namespace irmv::application {

// One semantic event of the supervision loop. The input router raises them
// (a bound byte of the keyboard table, an expiring velocity intent, a lost
// input device); this phase has no locomotion target generator, so
// `VelocityIntent` is delivered but the behaviour FSM has nothing to do for it.
//
// The definition lives in this header because the behaviour FSM is its only
// consumer in this phase: the input router includes this header for the type.
enum class InputEvent {
  None = 0,
  Damping,
  Initialize,
  ZeroTorque,
  EmergencyStop,
  Reset,
  Exit,
  VelocityIntent,
};

// The seven behaviours of the upper layer. `Ready` exists on its own so
// "still interpolating" and "a behaviour may be started" are observable, and it
// keeps being generated by the upper layer: once the upper process is gone the
// runtime falls back on its own target deadline instead of holding an old
// gain-carrying target forever. `Locomotion` keeps its enumerator and its entry
// guard, but this phase ships no target generator, so StartLocomotion() never
// enters it.
enum class BehaviorState {
  Starting,
  Standby,
  Damping,
  Initializing,
  Ready,
  Locomotion,
  Fault,
};

// What the behaviour FSM latched, and only that: the application-local cause of
// a Fault, kept separately from the runtime's own FaultReason (which the lower
// layer reports about itself and which the FSM never latches on the runtime's
// behalf). The latch is cleared only by a confirmed Reset.
//
// A lost input device is not one of these: the loop turns it into the same
// RequestExit an exit key raises, so the behaviour leaves through the bounded
// exit path and reports what it could not prove.
enum class FaultCause {
  None = 0,
  OperatorEmergencyStop,
  RuntimeFault,
  RuntimeUnreachable,
  RuntimeRestarted,
  InitializationFailed,
  RequestTimeout,
  UnexpectedContext,
};

// What one Step decided, and everything the loop displays. It carries no DDS
// type and no runtime type: the loop sends `command` through
// RobotClient::SendCommand, publishes a heartbeat when asked, and prints the
// rest.
struct BehaviorStep {
  // The behaviour after this iteration.
  BehaviorState state{BehaviorState::Starting};
  // The latched application-local cause; None while the FSM is not latched.
  FaultCause fault_cause{FaultCause::None};
  // The lower layer's own facts, as the last trustworthy state reported them.
  protocol::FaultReason runtime_fault_reason{protocol::FaultReason::None};
  protocol::StopReason runtime_stop_reason{protocol::StopReason::None};
  // False when no current state is known: the loop must display Unknown and
  // must not report the last remembered one as the runtime's present fact.
  bool runtime_state_known{false};
  protocol::ExecutionState runtime_state{protocol::ExecutionState::Boot};
  protocol::OutputAction runtime_output{protocol::OutputAction::ZeroTorque};
  // The reason of the last rejected request, kept for display.
  protocol::RejectReason last_reject_reason{protocol::RejectReason::None};
  // The initialization plan was refused by admission (the runtime would not
  // accept it): the FSM stayed in Damping, sent nothing and latched nothing.
  // Set for the step that decided it only.
  bool initialization_refused{false};
  // One target frame to send this iteration; `command` is complete except for
  // the routing identity RobotClient fills in (instance, session, send stamp).
  bool send_command{false};
  protocol::JointCommand command{};
  // A supervision heartbeat is due this iteration.
  bool send_heartbeat{false};
  // The exit sequence finished: the process may leave now.
  bool exit_ready{false};
  // ... and the damping stop was confirmed by a fresh lower state. False means
  // the stop was never proven, which the loop must report as Unknown (or as the
  // runtime's own fault), never as "damped".
  bool exit_stop_confirmed{false};
};

// The behaviour FSM and the serial supervision order of one iteration.
//
// It is a pure function of the view it is handed and of the times it is given:
// it reads no clock, allocates nothing, never throws, and touches no transport,
// no DDS type and no thread. The loop polls the client once, passes the view
// in, and then only sends what the Step returned and prints what it reported.
//
// The iteration is serial, in this order, and the order is the safety rule:
//
//   1. the fresh lower state and every fault it proves (latched, with the stop
//      a fault owes the machine);
//   2. the emergency stop and the exit, which do not wait for a confirmation;
//   3. the outcome of the pending request, then the ordinary requests and the
//      initialization targets;
//   4. last, and only after the checks above, the heartbeat decision.
//
// Every transition is gated on a matching confirmation: an Applied result the
// client accepted *and* a later fresh state that shows the target behaviour.
// The FSM never claims a motor executed anything, and never claims a stop that
// was not confirmed.
class BehaviorFsm {
 public:
  // `config` and `client` must outlive the FSM.
  BehaviorFsm(const configuration::ApplicationConfig &config,
              RobotClient &client);

  BehaviorFsm(const BehaviorFsm &) = delete;
  BehaviorFsm &operator=(const BehaviorFsm &) = delete;

  // One iteration: `now_us` is the host monotonic instant, `event` the semantic
  // input event of this iteration (None when there is none) and `view` the
  // ClientView of the Poll this iteration already made. Step never polls.
  BehaviorStep Step(protocol::TimeUs now_us, InputEvent event,
                    const ClientView &view);

  BehaviorState state() const { return state_; }
  FaultCause fault_cause() const { return fault_cause_; }

  // This phase has no locomotion target generator, so entering Locomotion is
  // not available: the call reports unavailable and changes nothing, Ready
  // included.
  bool StartLocomotion();

  // Starts the exit sequence: stop generating, cancel the pending request, ask
  // for Damping and wait for its confirmation for at most
  // supervision.request_deadline_us. The request itself leaves on the next
  // Step, which is the first call that can see whether the runtime is already
  // in Fault and must then keep its own output rule instead. Called by the exit
  // key, a signal and a lost input device.
  void RequestExit(protocol::TimeUs now_us);

 private:
  // What the one request the FSM may have outstanding is, and therefore what
  // its confirmation does to the behaviour.
  enum class Pending {
    None,
    Acquire,
    Damping,
    ZeroTorque,
    Tracking,
    Reset,
  };

  void FreshStateAndFaults(protocol::TimeUs now_us, const ClientView &view);
  void EmergencyStop(protocol::TimeUs now_us, const ClientView &view);
  // `outcome` is the request outcome this Step may act on: the view's own
  // outcome while this Step is the first to see that poll, and None otherwise.
  void ExitStep(protocol::TimeUs now_us, const ClientView &view,
                RequestOutcome outcome);
  void ConsumeOutcome(protocol::TimeUs now_us, const ClientView &view,
                      RequestOutcome outcome);
  // True when this iteration began a stop; such an iteration does not also
  // emit a target frame.
  bool OrdinaryRequests(protocol::TimeUs now_us, InputEvent event,
                        const ClientView &view, BehaviorStep *out);
  void TryStartInitialization(protocol::TimeUs now_us, const ClientView &view,
                              BehaviorStep *out);
  void TryReset(protocol::TimeUs now_us, const ClientView &view);
  void EmitTarget(protocol::TimeUs now_us, const ClientView &view,
                  BehaviorStep *out);

  // Latches `cause` (the first cause wins) and, when the fault owes the machine
  // a stop, asks for Damping unless a stop of ours is already on the wire.
  void LatchFault(FaultCause cause, protocol::TimeUs now_us, bool request_stop);
  bool BeginDampingStop(protocol::TimeUs now_us);
  bool BeginZeroTorqueStop(protocol::TimeUs now_us);
  bool BeginStop(protocol::Operation operation, Pending kind,
                 protocol::TimeUs now_us);
  bool BeginAcquire(protocol::TimeUs now_us);
  bool AcquireNeeded(protocol::TimeUs now_us, const ClientView &view) const;
  void CancelInitialization();
  bool StopPending() const;
  // Whether a Tracking state is the context this FSM authorized: the confirmed
  // initialization/hold context, or the context the pending Tracking request
  // proposes.
  bool ExpectedTracking(const protocol::RobotState &state) const;
  bool TargetDue(protocol::TimeUs now_us) const;
  bool HeartbeatDue(protocol::TimeUs now_us) const;

  const configuration::ApplicationConfig &config_;
  RobotClient &client_;
  // The producer the initialization trajectory and the Ready hold are published
  // under, fixed at construction.
  protocol::Id producer_id_{};

  // The initialization trajectory and the Ready hold, owned by value. The
  // generator latches its own progress and offers no cancel (Start refuses
  // while a move is in flight), so cancelling - which an ordinary stop, a
  // ZeroTorque stop, a fault and the exit all do - rebuilds it in place: the
  // optional is that storage and never allocates.
  std::optional<Initialization> initialization_;

  BehaviorState state_{BehaviorState::Starting};
  FaultCause fault_cause_{FaultCause::None};
  protocol::RejectReason last_reject_reason_{protocol::RejectReason::None};
  // The runtime's latched fault identity, kept for the explicit Reset; 0 while
  // no lower fault was observed.
  protocol::Sequence lower_fault_id_{0};

  Pending pending_{Pending::None};
  protocol::Id pending_producer_{};
  protocol::Sequence pending_epoch_{0};

  // The confirmed Tracking context the upper behaviour relies on.
  bool tracking_active_{false};
  protocol::Id tracking_producer_{};
  protocol::Sequence tracking_epoch_{0};

  // A state has been observed at least once; before that, Starting waits
  // instead of calling an absent link unreachable.
  bool saw_state_{false};
  // The serial of the poll whose outcome this FSM already consumed. The loop
  // hands one view to several Steps (one per input event), and the outcome is
  // edge triggered: without this a second Step would apply the same answer to a
  // request it began in the first one.
  protocol::Sequence consumed_poll_seq_{0};
  // The operation of the request the FSM began last, so a repeated key can tell
  // "the same stop is already on the wire" from "a different stop preempts".
  protocol::Operation pending_operation_{protocol::Operation::AcquireSession};
  // The last handover attempt, so a refused session is retried on the request
  // retry cadence instead of on every iteration.
  bool have_acquire_{false};
  protocol::TimeUs last_acquire_us_{0};
  bool have_target_{false};
  protocol::TimeUs last_target_us_{0};
  bool have_heartbeat_{false};
  protocol::TimeUs last_heartbeat_us_{0};

  bool exit_requested_{false};
  bool exit_ready_{false};
  bool exit_stop_confirmed_{false};
  protocol::TimeUs exit_deadline_us_{0};
};

}  // namespace irmv::application
